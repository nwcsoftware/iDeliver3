/* Seasonal themes for the customer app (supabase-fix133.sql).

   The office header already schedules a decorative banner; this is the same
   idea carried into the customer's phone, and further: as well as a background
   movie it repaints the app. The super admin picks one of the themes below,
   uploads a clip authored for a phone screen, and gives it a date window —
   Ramadan, Christmas, the height of summer.

   Only the ROLE colours change. The app paints with three of them (see
   tailwind.config.js): `shop` carries the actions, `fresh` the confirmations,
   `accent` the highlights. They resolve through CSS variables, so a theme is a
   handful of custom properties set on the root element and every existing
   class follows — no component knows a theme exists.

   Nothing here is required: with no theme scheduled the app looks exactly as
   it always has. */

/* ── the palette machinery ───────────────────────────────────────────────
   A theme is described by three seed colours, not by twenty-two. The ramp is
   generated by mixing the seed toward white and black, which keeps every theme
   internally consistent and makes adding one a three-colour job. */

const clamp = n => Math.max(0, Math.min(255, Math.round(n)))

export function hexToRgb(hex) {
  const h = String(hex || '').replace('#', '').trim()
  const full = h.length === 3 ? h.split('').map(c => c + c).join('') : h
  const n = parseInt(full, 16)
  if (!Number.isFinite(n) || full.length !== 6) return [0, 0, 0]
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

export const rgbToHex = ([r, g, b]) =>
  '#' + [r, g, b].map(v => clamp(v).toString(16).padStart(2, '0')).join('')

/* mix(a, b, t): t = 0 → a, t = 1 → b. */
const mix = (a, b, t) => a.map((v, i) => clamp(v + (b[i] - v) * t))

const WHITE = [255, 255, 255]
const BLACK = [17, 17, 17]

/* 50…900 from one seed. 600 is the seed itself — the app's primary weight. */
export function ramp(seedHex) {
  const seed = hexToRgb(seedHex)
  return {
    50:  mix(seed, WHITE, 0.94),
    100: mix(seed, WHITE, 0.86),
    200: mix(seed, WHITE, 0.70),
    300: mix(seed, WHITE, 0.50),
    400: mix(seed, WHITE, 0.28),
    500: mix(seed, WHITE, 0.12),
    600: seed,
    700: mix(seed, BLACK, 0.18),
    800: mix(seed, BLACK, 0.36),
    900: mix(seed, BLACK, 0.55),
  }
}

